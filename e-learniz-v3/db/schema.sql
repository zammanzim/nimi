-- ============================================================
-- E-Learniz v3 — SCHEMA (idempotent, aman dijalankan ulang)
-- ============================================================
-- File ini TIDAK menghapus data. Ia hanya:
--   • membuat schema/tabel yang belum ada,
--   • menambahkan kolom baru yang belum ada,
--   • menyegarkan function, trigger, RLS policy, dan grant.
--
-- Kalau memang ingin reset total (hapus semua data v3), jalankan
-- db/reset.sql secara sadar, lalu db/schema.sql + db/seed.sql.
--
-- Arsitektur:
--   • Siswa : login "pilih nama" (localStorage) — tanpa password.
--   • Staff : Supabase Auth (email + password) → v3.users.auth_user_id.
--
-- RLS (wewenang tulis ditentukan SERVER, bukan localStorage):
--   • anon          : SELECT semua tabel + tulis task_progress & visitors.
--   • authenticated : staff (cek v3.is_staff()) boleh tulis konten.
--
-- WAJIB sekali setup: Dashboard → Project Settings → API →
--   Exposed schemas → tambah "v3" → Save.
-- ============================================================

begin;

create schema if not exists v3;
grant usage on schema v3 to anon, authenticated, service_role;

-- ─────────────────────────────────────────────
-- TABEL
-- ─────────────────────────────────────────────

-- Kelas
create table if not exists v3.classes (
    id            bigint generated by default as identity primary key,
    name          text not null,
    academic_year text not null default '2026/2027',
    is_active     boolean not null default true
);

-- Users: siswa (pick-name) + staff (nyambung ke Supabase Auth)
create table if not exists v3.users (
    id           bigint generated by default as identity primary key,
    class_id     bigint references v3.classes(id) on delete set null,
    nickname     text not null,
    full_name    text default '',
    role         text not null default 'student'
                 check (role in ('student', 'teacher', 'class_admin', 'super_admin')),
    auth_user_id uuid unique references auth.users(id) on delete set null,
    avatar_url   text default '',
    created_at   timestamptz not null default now()
);

-- Mapel per kelas (urutan + info guru nempel di sini)
create table if not exists v3.subjects (
    id              bigint generated by default as identity primary key,
    class_id        bigint not null references v3.classes(id) on delete cascade,
    slug            text not null,
    name            text not null,
    icon            text not null default 'fa-book',
    color           text not null default '#2563eb',
    teacher_name    text default '',
    teacher_contact text default '',
    urutan          int not null default 99,
    locked          boolean not null default false,
    created_at      timestamptz not null default now(),
    unique (class_id, slug)
);

-- Cards: pengumuman + materi/tugas (satu tabel)
--   subject_id NULL + kind 'pengumuman' = pengumuman kelas
--   has_task true = kartu bisa dicentang selesai (tugas)
create table if not exists v3.cards (
    id          bigint generated by default as identity primary key,
    class_id    bigint not null references v3.classes(id) on delete cascade,
    subject_id  bigint references v3.subjects(id) on delete cascade,
    kind        text not null default 'pengumuman'
                check (kind in ('pengumuman', 'materi', 'tugas')),
    has_task    boolean not null default false,
    big_title   text default '',
    title       text default '',
    content     text default '',
    small       text default '',
    media       jsonb not null default '[]',
    is_pinned   boolean not null default false,
    urutan      int not null default 99,
    task_due    timestamptz,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

-- Centang tugas per siswa
create table if not exists v3.task_progress (
    user_id    bigint not null references v3.users(id) on delete cascade,
    card_id    bigint not null references v3.cards(id) on delete cascade,
    done       boolean not null default true,
    updated_at timestamptz not null default now(),
    primary key (user_id, card_id)
);

-- Pengunjung (1 baris per user, upsert by user_id)
create table if not exists v3.visitors (
    user_id    bigint primary key references v3.users(id) on delete cascade,
    class_id   bigint references v3.classes(id) on delete cascade,
    last_page  text default '',
    is_visible boolean not null default true,
    visited_at timestamptz not null default now()
);

-- Jadwal (daily card): info per hari
create table if not exists v3.schedule_days (
    id        bigint generated by default as identity primary key,
    class_id  bigint not null references v3.classes(id) on delete cascade,
    weekday   int not null check (weekday between 1 and 7),
    is_school boolean not null default true,
    uniform   text default '',
    picket    text default '',
    activity  text default '',
    notes     text default '',
    unique (class_id, weekday)
);

-- Jadwal (daily card): baris periode pelajaran per hari
create table if not exists v3.schedule_periods (
    id         bigint generated by default as identity primary key,
    class_id   bigint not null references v3.classes(id) on delete cascade,
    weekday    int not null check (weekday between 1 and 7),
    urutan     int not null default 99,
    time_start text default '',
    time_end   text default '',
    label      text not null,
    kind       text not null default 'belajar'
               check (kind in ('belajar', 'istirahat', 'kegiatan', 'pulang')),
    subject_id bigint references v3.subjects(id) on delete set null,
    unique (class_id, weekday, urutan)
);

-- ─────────────────────────────────────────────
-- KOLOM BARU / PENYESUAIAN DATA LAMA
-- (aman dijalankan pada database yang sudah berisi)
-- ─────────────────────────────────────────────
alter table v3.subjects
    add column if not exists color text;
-- Isi warna kosong dengan palet yang sama seperti fallback UI.
with ranked as (
    select id,
           row_number() over (partition by class_id order by urutan, id) as rn
    from v3.subjects
    where color is null or btrim(color) = ''
)
update v3.subjects s
set color = (array['#2563eb', '#0ea5e9', '#10b981', '#f59e0b', '#8b5cf6', '#f43f5e', '#14b8a6'])[((r.rn - 1) % 7) + 1]
from ranked r
where s.id = r.id;
update v3.subjects set color = '#2563eb' where color is null or btrim(color) = '';
alter table v3.subjects alter column color set default '#2563eb';
alter table v3.subjects alter column color set not null;

alter table v3.cards
    add column if not exists has_task boolean;
update v3.cards set has_task = true where kind = 'tugas' and has_task is distinct from true;
update v3.cards set has_task = false where has_task is null;
alter table v3.cards alter column has_task set default false;
alter table v3.cards alter column has_task set not null;

-- task_due harus menyimpan tanggal + jam (bukan date saja)
alter table v3.cards
    alter column task_due type timestamptz using task_due::timestamptz;

alter table v3.schedule_periods
    add column if not exists subject_id bigint references v3.subjects(id) on delete set null;

-- Backfill aman: cocokkan nama yang sama persis atau alias umum.
-- Tidak memakai fuzzy matching agar "PP" tidak salah cocok ke "PPK".
update v3.schedule_periods p
set subject_id = s.id
from v3.subjects s
where p.subject_id is null
  and p.kind = 'belajar'
  and p.class_id = s.class_id
  and lower(btrim(p.label)) = lower(btrim(s.name));

with alias_map(label, slug) as (
    values
        ('Bahasa Indonesia', 'bahasaindonesia'),
        ('Bahasa Inggris', 'bahasainggris'),
        ('Bahasa Sunda', 'bahasasunda'),
        ('Bahasa Jepang', 'bahasajepang'),
        ('B. Indonesia', 'bahasaindonesia'),
        ('B. Inggris', 'bahasainggris'),
        ('B. Sunda', 'bahasasunda'),
        ('B. Jepang', 'bahasajepang'),
        ('MTK', 'matematika')
)
update v3.schedule_periods p
set subject_id = s.id
from alias_map a
join v3.subjects s on s.slug = a.slug
where p.subject_id is null
  and p.kind = 'belajar'
  and p.class_id = s.class_id
  and lower(btrim(p.label)) = lower(a.label);

-- ─────────────────────────────────────────────
-- INDEX
-- ─────────────────────────────────────────────
create index if not exists cards_class_idx on v3.cards (class_id);
create index if not exists cards_subject_idx on v3.cards (subject_id);
create index if not exists schedule_periods_class_idx on v3.schedule_periods (class_id, weekday);
create index if not exists schedule_periods_subject_idx on v3.schedule_periods (subject_id);
create index if not exists visitors_class_idx on v3.visitors (class_id, visited_at desc);

-- ─────────────────────────────────────────────
-- HELPER + TRIGGER
-- ─────────────────────────────────────────────

-- Cek staff dari JWT (security definer → bypass RLS v3.users, anti rekursi)
create or replace function v3.is_staff()
returns boolean
language sql stable security definer set search_path = v3
as $$
    select exists (
        select 1 from v3.users u
        where u.auth_user_id = auth.uid()
          and u.role in ('teacher', 'class_admin', 'super_admin')
    );
$$;

-- auto updated_at
create or replace function v3.touch_updated_at()
returns trigger language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end $$;

drop trigger if exists cards_touch on v3.cards;
create trigger cards_touch before update on v3.cards
    for each row execute function v3.touch_updated_at();

-- ─────────────────────────────────────────────
-- RLS
-- ─────────────────────────────────────────────
alter table v3.classes          enable row level security;
alter table v3.users            enable row level security;
alter table v3.subjects         enable row level security;
alter table v3.cards            enable row level security;
alter table v3.task_progress    enable row level security;
alter table v3.visitors         enable row level security;
alter table v3.schedule_days    enable row level security;
alter table v3.schedule_periods enable row level security;

-- Bersihkan policy lama supaya file ini bisa dijalankan ulang tanpa
-- bentrok nama/aturan dari versi sebelumnya.
do $$
declare
    pol record;
begin
    for pol in
        select schemaname, tablename, policyname
        from pg_policies
        where schemaname = 'v3'
    loop
        execute format('drop policy if exists %I on %I.%I',
                       pol.policyname, pol.schemaname, pol.tablename);
    end loop;
end $$;

-- baca: bebas buat semua (konten sekolah = publik)
create policy read_all on v3.classes          for select to anon, authenticated using (true);
create policy read_all on v3.users            for select to anon, authenticated using (true);
create policy read_all on v3.subjects         for select to anon, authenticated using (true);
create policy read_all on v3.cards            for select to anon, authenticated using (true);
create policy read_all on v3.task_progress    for select to anon, authenticated using (true);
create policy read_all on v3.visitors         for select to anon, authenticated using (true);
create policy read_all on v3.schedule_days    for select to anon, authenticated using (true);
create policy read_all on v3.schedule_periods for select to anon, authenticated using (true);

-- tulis konten: cuma staff login (JWT). Siswa tidak bisa walau localStorage dioprek.
create policy staff_write on v3.classes          for all to authenticated using (v3.is_staff()) with check (v3.is_staff());
create policy staff_write on v3.users            for all to authenticated using (v3.is_staff()) with check (v3.is_staff());
create policy staff_write on v3.subjects         for all to authenticated using (v3.is_staff()) with check (v3.is_staff());
create policy staff_write on v3.cards            for all to authenticated using (v3.is_staff()) with check (v3.is_staff());
create policy staff_write on v3.schedule_days    for all to authenticated using (v3.is_staff()) with check (v3.is_staff());
create policy staff_write on v3.schedule_periods for all to authenticated using (v3.is_staff()) with check (v3.is_staff());

-- fitur ringan siswa (centang tugas + log pengunjung): tulis bebas
create policy upsert_write on v3.task_progress for insert to anon, authenticated with check (true);
create policy upsert_mod   on v3.task_progress for update to anon, authenticated using (true) with check (true);
create policy upsert_del   on v3.task_progress for delete to anon, authenticated using (true);
create policy upsert_write on v3.visitors      for insert to anon, authenticated with check (true);
create policy upsert_mod   on v3.visitors      for update to anon, authenticated using (true) with check (true);
create policy upsert_del   on v3.visitors      for delete to anon, authenticated using (true);

-- ─────────────────────────────────────────────
-- GRANT (schema custom butuh grant eksplisit buat PostgREST)
-- ─────────────────────────────────────────────
grant select on v3.classes, v3.users, v3.subjects, v3.cards, v3.task_progress, v3.visitors,
    v3.schedule_days, v3.schedule_periods
    to anon, authenticated;
grant insert, update, delete on v3.task_progress, v3.visitors to anon, authenticated;
grant insert, update, delete on v3.classes, v3.users, v3.subjects, v3.cards,
    v3.schedule_days, v3.schedule_periods to authenticated;
grant usage, select on all sequences in schema v3 to anon, authenticated;
alter default privileges in schema v3 grant usage, select on sequences to anon, authenticated;

-- refresh cache PostgREST
notify pgrst, 'reload schema';

commit;
